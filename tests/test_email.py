from dataclasses import replace
from pathlib import Path

from gentoo_reminders.collectors.base import Item, Section
from gentoo_reminders.config import Config
from gentoo_reminders.email import render, send_outbox
from gentoo_reminders.maintainers import Maintainer

CONFIG = Config(gentoo_repo=Path("/nonexistent"))
MAINTAINER = Maintainer("x11@gentoo.org", packages=["x11-libs/libdrm"])
SECTIONS = [
    Section("Open Bugs", [
        Item("Bug #1", ": <b> & ünïcode", "https://bugs.gentoo.org/1"),
        Item("Bug #2", ": " + "long " * 30),
    ]),
    Section("Recent Changes", text="A U Thor (1):\n      x11-libs/libdrm: add 1.0"),
]


def test_headers():
    msg = render(CONFIG, MAINTAINER, SECTIONS)

    assert msg["To"] == "x11@gentoo.org"
    assert msg["From"] == "noreply@gentoo.org"
    assert msg["Subject"] == "[Gentoo Reminder] Your package maintenance summary"
    assert msg["Message-ID"].endswith("@gentoo.org>")


def test_text_body():
    msg = render(replace(CONFIG, multipart=False), MAINTAINER, SECTIONS)

    assert msg.get_content() == """\
Hi x11@gentoo.org,

Here is your monthly Gentoo package maintenance summary.
You maintain 1 package.

== Open Bugs (2) ==

  Bug #1: <b> & ünïcode
  Bug #2: {LONG}

== Recent Changes ==
A U Thor (1):
      x11-libs/libdrm: add 1.0

--
Generated by gentoo-reminders
""".replace("{LONG}", "long " * 30)
    # Readable without decoding
    assert "ünïcode".encode() in msg.as_bytes()


def test_html_alternative():
    msg = render(CONFIG, MAINTAINER, SECTIONS)

    text, html = msg.iter_parts()
    assert text.get_content_type() == "text/plain"
    assert html.get_content_type() == "text/html"
    assert ('<li><a href="https://bugs.gentoo.org/1">Bug #1</a>: &lt;b&gt; &amp; ünïcode</li>'
            in html.get_content())
    assert "<pre>A U Thor (1):\n      x11-libs/libdrm: add 1.0</pre>" in html.get_content()


def test_long_line_encoded():
    sections = [Section("Open Bugs", [Item("Bug #1", ": " + "x" * 1000)])]
    msg = render(replace(CONFIG, multipart=False), MAINTAINER, sections)

    assert msg["Content-Transfer-Encoding"] == "quoted-printable"
    assert max(map(len, msg.as_bytes().splitlines())) <= 998


def outbox(tmp_path):
    for name in ("fails", "works"):
        maintainer = replace(MAINTAINER, email=f"{name}@gentoo.org")
        msg = render(replace(CONFIG, multipart=False), maintainer, SECTIONS)
        (tmp_path / f"{name}.eml").write_bytes(msg.as_bytes())


def test_send_outbox(tmp_path):
    outbox(tmp_path)
    sendmail = tmp_path / "sendmail"
    log = tmp_path / "log"
    # Fails for one recipient, and records the arguments and message otherwise
    sendmail.write_text(f"""#!/bin/sh
msg=$(cat)
case "$msg" in *"To: fails@"*) echo nope >&2; exit 75;; esac
echo "$@" >> {log}
echo "$msg" >> {log}
""")
    sendmail.chmod(0o755)

    assert send_outbox(tmp_path, str(sendmail)) == 1
    assert [p.name for p in tmp_path.glob("*.eml")] == ["fails.eml"]
    assert [p.name for p in (tmp_path / "sent").iterdir()] == ["works.eml"]
    assert log.read_text().startswith("-t -oi\n")
    assert "To: works@gentoo.org" in log.read_text()


def test_send_outbox_dry_run(tmp_path):
    outbox(tmp_path)
    assert send_outbox(tmp_path, "/nonexistent", dry_run=True) == 0
    assert sorted(p.name for p in tmp_path.iterdir()) == ["fails.eml", "works.eml"]
